#!/usr/bin/env python3
"""Build the public SmartCharge site from the idea-page fragments.

The pages in buca1821/SmartCharge (docs/producto/la-idea-de-smartcharge*.html)
are artifact fragments: no doctype, no <html>, no <head>, no viewport. The
GitHub Pages site at https://smartchargeapp.github.io serves them as full
documents: doctype, html lang, head metadata, viewport, and language links that
point at /, /ca/ and /en/.

Usage:
    python3 build-site.py /path/to/SmartCharge/docs/producto /path/to/pages-repo

It writes index.html, ca/index.html and en/index.html in the pages repository.
The favicon and apple-touch-icon are committed once and not regenerated here.
"""

from __future__ import annotations

import html
import re
import sys
from pathlib import Path

BASE_URL = "https://smartchargeapp.github.io"

PAGES = [
    dict(suffix="html", lang="es", out="index.html", path="/", locale="es_ES",
         source="la-idea-de-smartcharge.html"),
    dict(suffix="ca", lang="ca", out="ca/index.html", path="/ca/", locale="ca_ES",
         source="la-idea-de-smartcharge.ca.html"),
    dict(suffix="en", lang="en", out="en/index.html", path="/en/", locale="en_GB",
         source="la-idea-de-smartcharge.en.html"),
]

# The fragments link to each other by file name; the site has clean URLs.
LINKS = {
    "la-idea-de-smartcharge.html": "/",
    "la-idea-de-smartcharge.ca.html": "/ca/",
    "la-idea-de-smartcharge.en.html": "/en/",
}


def strip_tags(value: str) -> str:
    return html.unescape(re.sub(r"<[^>]+>", "", value)).strip()


def build(source_dir: Path, pages_root: Path) -> None:
    for page in PAGES:
        source = source_dir / page["source"]
        text = source.read_text(encoding="utf-8")

        title = re.search(r"<title>(.*?)</title>", text, re.S).group(1).strip()
        lead = strip_tags(re.search(r'<p class="lead">(.*?)</p>', text, re.S).group(1))
        style = text[text.index("<style>"):text.index("</style>") + len("</style>")]
        fonts = re.search(
            r'<link rel="stylesheet" href="https://fonts\.googleapis\.com[^"]+">', text
        ).group(0)
        body = text[text.index('<div class="page"'):].strip()
        for old, new in LINKS.items():
            body = body.replace(f'href="{old}"', f'href="{new}"')

        description = html.escape(lead, quote=True)
        document = f"""<!doctype html>
<html lang="{page['lang']}">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<title>{html.escape(title)}</title>
<!-- Generated by build-site.py from buca1821/SmartCharge docs/producto/{page['source']}.
     Do not edit by hand: change the source page and rebuild. -->
<meta name="description" content="{description}">
<meta name="theme-color" content="#f3f5f9">
<meta name="robots" content="noindex, nofollow">
<meta property="og:type" content="website">
<meta property="og:site_name" content="SmartCharge">
<meta property="og:title" content="{html.escape(title, quote=True)}">
<meta property="og:description" content="{description}">
<meta property="og:url" content="{BASE_URL}{page['path']}">
<meta property="og:locale" content="{page['locale']}">
<meta name="twitter:card" content="summary">
<link rel="icon" type="image/png" href="/favicon.png">
<link rel="apple-touch-icon" href="/apple-touch-icon.png">
{fonts}
{style}
</head>
<body>
{body}
</body>
</html>
"""
        target = pages_root / page["out"]
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(document, encoding="utf-8")
        print(f"wrote {target} ({len(document)} bytes)")


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__)
        return 2
    source_dir = Path(sys.argv[1]).resolve()
    pages_root = Path(sys.argv[2]).resolve()
    for page in PAGES:
        if not (source_dir / page["source"]).is_file():
            print(f"missing source page: {source_dir / page['source']}", file=sys.stderr)
            return 1
    build(source_dir, pages_root)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
